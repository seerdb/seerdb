        self.assertEqual(len(Exists), len(Close))
        Differ = [At for At, (A, B) in enumerate(zip(Exists, Close)) if A != B]
        self.assertEqual(len(Differ), 2)
        self.assertEqual((Close[Differ[0]], Exists[Differ[0]]), (0, 1))


