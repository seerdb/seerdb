        for At, (Theirs, Mine) in enumerate(zip(self.REQUEST, ours)):
            if At not in Masked:
                self.assertEqual(Mine, Theirs, f'byte {At}')
        self.assertNotEqual(bytes(ours[59:67]), bytes(8))

